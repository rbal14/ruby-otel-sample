module Internal
  # Stands in for the marketing-site webhook that drops new leads into the
  # platform. CSRF-exempt JSON so the load generator (and curl) can drive it.
  class SimulationsController < ApplicationController
    skip_forgery_protection

    FIRST_NAMES = %w[Alex Jordan Casey Morgan Riley Taylor Devon Shannon Priya Tomas Nia Kwame].freeze
    LAST_NAMES  = %w[Reyes Okafor Lindqvist Whitfield Nakamura Duarte Kowalski Haddad Calloway Osei].freeze
    ZIPS        = %w[19103 19013 21201 22030 28202 37203 75201 80202 11530 02108].freeze
    SOURCES     = %w[web_form canvassing home_show referral inbound_call direct_mail].freeze
    PRODUCTS    = %w[windows siding doors roofing gutters attic_insulation].freeze

    # POST /internal/leads
    # Body is optional -- with no payload a plausible lead is generated, which
    # is what makes this usable as a traffic source.
    def create_lead
      attributes = lead_attributes
      created = api_client.create_lead(attributes)

      # Hand off to Sidekiq. The HTTP response returns before the worker runs.
      LeadScoringJob.perform_later(created["id"])

      render json: { created_lead_id: created["id"], enqueued: "LeadScoringJob", lead: created },
             status: :created
    end

    private

    def lead_attributes
      supplied = params.fetch(:lead, nil)
      return supplied.permit(:first_name, :last_name, :email, :phone, :zip_code,
                             :source, :product_interest, :estimated_value, :notes).to_h if supplied.present?

      suffix = SecureRandom.hex(4)
      {
        first_name: FIRST_NAMES.sample,
        last_name: LAST_NAMES.sample,
        email: "sim-#{suffix}@example-phr.test",
        phone: format("215-555-%04d", rand(10_000)),
        zip_code: ZIPS.sample,
        source: SOURCES.sample,
        product_interest: PRODUCTS.sample,
        estimated_value: rand(4_000..48_000),
        notes: "Generated by the load simulator at #{Time.current.iso8601}."
      }
    end
  end
end
